def normalize_tags(tags: list[str]) -> list[str]:
    """Local formatting/dedup only; never invent tags or buy a rewrite for a deficit."""
    result, seen = [], set()
    for raw in tags:
        tag = re.sub(r'\s+', '', str(raw).strip().lstrip('#'))
        key = tag.casefold()
        if (not re.fullmatch(r'[가-힣A-Za-z0-9]+', tag)
                or re.fullmatch(r'(?:태그|해시태그|tag)?\d+', key)
                or key in seen):
            continue
        seen.add(key)
        result.append(tag)
    return result[:8]


def tag_hints(tags: list[str], content: str) -> list[str]:
    """Nonblocking observations; semantic relevance remains a source/body review."""
    clean = normalize_tags(tags)
    hints = []
    if len(clean) < 5:
        hints.append(f'{TAG_EDIT_PREFIX} 유효 태그 {len(clean)}개, 최소 5개 미충족. 관련 태그만 근거 있게 보충 필요.')
    if clean != tags:
        hints.append(f'{TAG_EDIT_PREFIX} 태그 표기·중복·번호·최대 8개를 국소 정리한다.')
    text = re.sub(r'\s+', '', content).casefold()
    unanchored = [tag for tag in clean if tag.casefold() not in text]
    if unanchored:
        hints.append(f'{TAG_EDIT_PREFIX} 본문 직접 표기 없는 태그의 관련성·동의어 중복을 문맥으로 대조: '
                     + ', '.join(unanchored) + '. 개수 충족만으로 관련성을 승인하지 않는다.')
    return hints
